// ✅ TS1: знак = ближайший (евклидово) архетип; ничья — первый по порядку
export function zodiacOf(pers) {
  let best = null, bd = Infinity;
  for (const [k, z] of Object.entries(ZODIAC)) {
    const d = AXES.reduce((s, a, i) => s + (pers[a] - z.p[i]) ** 2, 0);
    if (d < bd) { bd = d; best = k; }
  }
  return best;
}

