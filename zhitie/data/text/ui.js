// Подстановка шаблона
export function fmt(keyOrTpl, vars = {}) {
  const tpl = NOTIFY[keyOrTpl]?.text ?? keyOrTpl;
  return tpl
    .replace(/\[([^|\]]*)\|([^\]]*)\]/g, (_, m, f) => (vars.female ? f : m))
    .replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''))
    .replace(/\s+$/, '');
}
